"""
backend.agents.fix_plan_orchestrator - the Fix-with-AI flow for Talent Acquisition.

    finding_id (RC-T1-01-2)
        -> resolve the stored root cause and derive its deterministic selectors   [SQL]
        -> (1) impacted cases and their metrics                                   [SQL]
        -> (2) the KPIs those cases move, impacted vs unimpacted                  [SQL]
        -> (3) the most representative case, deterministically scored             [SQL + pure fn]
        -> (4) what happened in it: journey, key events, factual narrative        [SQL]
        -> (5) the specialist agents to invoke, from the deterministic mapping    [config]
        -> return

The split is the point: everything countable is computed here in SQL, and nothing in this
response is generated by a model. If there are no impacted cases, the flow stops early and says
so rather than returning an empty shell.

A model-written remediation plan is a deliberate NEXT step, not part of this module. When it is
added it takes this payload as its input and may only interpret it - the figures, the case
selection and the narrative stay deterministic, which is what makes them auditable.
"""
from __future__ import annotations

import datetime as _dt
from typing import Optional

from .. import db
from ..services import (event_log_service, fix_selectors, impact_service, kpi_context_service,
                        representative_case)
from ..services import root_cause_store
from . import recommendation_agent


class RootCauseNotFound(LookupError):
    """No such root cause in the stored analysis."""


class InsufficientEvidence(ValueError):
    """The root cause carries no selectors, so it cannot be tied to cases in the event log."""


def _now() -> str:
    return _dt.datetime.now().isoformat(sep=" ", timespec="seconds")


def _root_cause_out(finding: dict, selectors: dict) -> dict:
    return {
        "finding_id": finding.get("finding_id"),
        "analysis_id": finding.get("analysis_id"),
        "run_id": finding.get("run_id"),
        "rank": finding.get("rank"),
        "root_cause": finding.get("root_cause"),
        "root_cause_type": finding.get("root_cause_type"),
        "confidence": finding.get("confidence"),
        "root_cause_summary": finding.get("root_cause_summary"),
        "impact_summary": finding.get("impact_summary"),
        "causal_explanation": finding.get("causal_explanation"),
        "evidence_limitations": finding.get("evidence_limitations"),
        "tier1_kpi_id": finding.get("tier1_kpi_id"),
        "tier1_kpi_name": finding.get("tier1_kpi_name"),
        "tier1_cohort_rule": finding.get("tier1_cohort_rule"),
        "gap_references": selectors.get("gap_references"),
        "tier2_kpi_ids": selectors.get("tier2_kpi_ids"),
        "affected_case_type": finding.get("affected_case_type"),
        "recommended_interventions": finding.get("recommended_interventions") or [],
    }


def run(finding_id: str, analysis_id: Optional[int] = None, conn=None,
        candidates: int = 5, include_timeline: bool = True) -> dict:
    """Build the full Fix-with-AI payload for one root cause."""
    if conn is not None:
        return _run(conn, finding_id, analysis_id, candidates, include_timeline)
    with db.connection() as c:
        return _run(c, finding_id, analysis_id, candidates, include_timeline)


def _run(conn, finding_id: str, analysis_id, candidates: int, include_timeline: bool) -> dict:
    finding = root_cause_store.get_finding(conn, finding_id.upper(), analysis_id)
    if not finding:
        raise RootCauseNotFound(
            f"No root cause {finding_id.upper()} in the stored analysis. Ids are "
            f"RC-<tier1 kpi>-<rank>, e.g. RC-T1-01-1.")

    selectors = fix_selectors.extract(finding)
    if not fix_selectors.has_evidence(selectors):
        raise InsufficientEvidence(
            f"{finding_id.upper()} cites no activity and no gap, so it cannot be tied to cases in "
            f"the event log. Re-run root_cause_agent.py - a root cause without activity or gap "
            f"evidence should not have passed validation.")

    run_id = finding.get("run_id")

    # (1) impacted cases
    impact = impact_service.calculate(conn, selectors, run_id)

    # (2) the KPIs those cases move
    kpis = kpi_context_service.build(conn, selectors, run_id)

    # (5) which specialist agents own the remediation. Deterministic: the mapping is
    # version-controlled in recommendation_agent, and no model selects an agent id.
    detections = {g["gap_reference"]: g for g in (kpis.get("gaps") or [])
                  if isinstance(g.get("detected"), dict)}
    detections = {k: {"cases": (v.get("detected") or {}).get("cases") or 0}
                  for k, v in detections.items()}
    agents = recommendation_agent.recommend_for_finding(
        finding,
        tier1_rows=[kpis["tier1"]] if kpis.get("tier1") else [],
        tier2_rows=kpis.get("tier2") or [],
        gap_rows=kpis.get("gaps") or [],
        detections=detections,
        stage_code=next(iter(selectors.get("stage_codes") or []), None))

    payload = {
        "generated_at": _now(),
        "finding_id": finding_id.upper(),
        "source": "deterministic",
        "selectors": selectors,
        "root_cause": _root_cause_out(finding, selectors),
        "impact": impact,
        "kpis": kpis,
        "representative_case": None,
        "what_happened": None,
        "agents": agents,
        "notes": list(impact.get("notes") or []),
    }

    if not impact.get("impacted_cases"):
        payload["notes"].append(
            "No representative case could be selected because no case matches this root cause.")
        return payload

    # (3) the most representative case
    selection = representative_case.select(conn, selectors, top_n=candidates)
    payload["representative_case"] = selection
    if selection.get("note"):
        payload["notes"].append(selection["note"])

    case = (selection or {}).get("case")
    if not case:
        return payload

    # (4) what happened in it
    story = event_log_service.what_happened(conn, case["case_id"], selectors)
    if not include_timeline:
        story.pop("timeline", None)
    payload["what_happened"] = story
    return payload
